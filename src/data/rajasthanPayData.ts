// Rajasthan SI (State Insurance - राज्य बीमा) Mandatory monthly premium slabs
export function getRajasthanSiSlab(basicPay: number): { min: number; slab1: number; slab2: number } {
  if (basicPay <= 23100) return { min: 800, slab1: 1200, slab2: 2200 };
  if (basicPay <= 28500) return { min: 1200, slab1: 2200, slab2: 3000 };
  if (basicPay <= 38500) return { min: 2200, slab1: 3000, slab2: 5000 };
  if (basicPay <= 51500) return { min: 3000, slab1: 5000, slab2: 7000 };
  if (basicPay <= 62000) return { min: 5000, slab1: 7000, slab2: 7000 };
  return { min: 7000, slab1: 7000, slab2: 7000 };
}

